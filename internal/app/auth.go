	a.handle("GET /api/auth/sessions", func(w http.ResponseWriter, r *http.Request) error {
		currentKey := a.requestSessionKey(r)
		a.Store.mu.Lock()
		rows, err := a.Store.db.Query("SELECT key,value FROM documents WHERE kind='sessions'")
		if err != nil {
			a.Store.mu.Unlock()
			return err
		}
		type item struct {
			key string
			obj Obj
		}
		var rawItems []item
		var expiredKeys []string
		nowUnix := time.Now().Unix()
		for rows.Next() {
			var key, raw string
			if err := rows.Scan(&key, &raw); err != nil {
				continue
			}
			var s Obj
			if json.Unmarshal([]byte(raw), &s) != nil || s == nil {
				continue
			}
			if num(s["expires"]) <= nowUnix {
				expiredKeys = append(expiredKeys, key)
				continue
			}
			rawItems = append(rawItems, item{key: key, obj: s})
		}
		rows.Close()
		a.Store.mu.Unlock()

		for _, key := range expiredKeys {
			_ = a.Store.Delete("sessions", key)
		}

		sessions := make([]Obj, 0, len(rawItems))
		for _, it := range rawItems {
			s := it.obj
			method := str(s["authMethod"])
			if method == "" {
				if str(s["githubLogin"]) != "" {
					method = "github"
				} else {
					method = "password"
				}
			}
			device := str(s["deviceName"])
			if device == "" {
				if gh := str(s["githubLogin"]); gh != "" {
					device = "GitHub (" + gh + ")"
				} else {
					device = describeUserAgent(str(s["userAgent"]))
				}
			}
			sessions = append(sessions, Obj{
				"id":          num(s["id"]),
				"deviceName":  device,
				"userAgent":   str(s["userAgent"]),
				"ipAddress":   str(s["ipAddress"]),
				"authMethod":  method,
				"githubLogin": str(s["githubLogin"]),
				"githubId":    str(s["githubId"]),
				"createdAt":   str(s["createdAt"]),
				"lastSeenAt":  str(s["lastSeenAt"]),
				"expiresAt":   str(s["expiresAt"]),
				"current":     currentKey != "" && it.key == currentKey,
			})
		}

		sort.Slice(sessions, func(i, j int) bool {
			ci, cj := flag(sessions[i]["current"]), flag(sessions[j]["current"])
			if ci != cj {
				return ci
			}
			return str(sessions[i]["lastSeenAt"]) > str(sessions[j]["lastSeenAt"])
		})
		ok(w, sessions)
		return nil
	})

	a.handle("DELETE /api/auth/sessions/{id}", func(w http.ResponseWriter, r *http.Request) error {
		targetID := strings.TrimSpace(r.PathValue("id"))
		currentKey := a.requestSessionKey(r)
		a.Store.mu.Lock()
		rows, err := a.Store.db.Query("SELECT key,value FROM documents WHERE kind='sessions'")
		if err != nil {
			a.Store.mu.Unlock()
			return err
		}
		var keys []string
		for rows.Next() {
			var key, raw string
			_ = rows.Scan(&key, &raw)
			var s Obj
			if json.Unmarshal([]byte(raw), &s) == nil && s != nil {
				if strconv.FormatInt(num(s["id"]), 10) == targetID || str(s["id"]) == targetID {
					keys = append(keys, key)
				}
			}
		}
		rows.Close()
		a.Store.mu.Unlock()

		revokedCurrent := false
		for _, key := range keys {
			if key == currentKey {
				revokedCurrent = true
			}
			if err := a.Store.Delete("sessions", key); err != nil {
				return err
			}
		}
		if revokedCurrent {
			clearSessionCookie(w, r)
		}
		ok(w, Obj{"revoked": len(keys) > 0, "current": revokedCurrent})
		return nil
	})

	a.handle("POST /api/auth/sessions/revoke-others", func(w http.ResponseWriter, r *http.Request) error {
		currentKey := a.requestSessionKey(r)
		a.Store.mu.Lock()
		rows, err := a.Store.db.Query("SELECT key FROM documents WHERE kind='sessions'")
		if err != nil {
			a.Store.mu.Unlock()
			return err
		}
		var keys []string
		for rows.Next() {
			var key string
			if rows.Scan(&key) == nil && key != currentKey {
				keys = append(keys, key)
			}
		}
		rows.Close()
		a.Store.mu.Unlock()

		for _, key := range keys {
			if err := a.Store.Delete("sessions", key); err != nil {
				return err
			}
		}
		ok(w, Obj{"revoked": len(keys)})
		return nil
	})

	a.handle("POST /api/auth/logout", func(w http.ResponseWriter, r *http.Request) error {
		if c, err := r.Cookie(authSessionCookieName); err == nil && c.Value != "" {
			_ = a.Store.Delete("sessions", hash(c.Value))
		}
		if token := strings.TrimPrefix(r.Header.Get("Authorization"), "Bearer "); token != "" {
			_ = a.Store.Delete("sessions", hash(token))
		}
		clearSessionCookie(w, r)
		ok(w, Obj{"revoked": true})
		return nil
	})
